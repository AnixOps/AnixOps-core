/// One entry of [`ManagedStatus::static_keys`].
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct NetworkStaticKey {
    /// The network's `network.name`.
    pub network: String,
    /// The key, encoded like the snapshot's `self.staticKey`.
    pub static_key: String,
}

/// Why a network does not run, or the last thing refused in it: the
/// snapshot's `network.failure` (`docs/architecture/mesh-status.md`,
/// "失败与冲突原因").
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct NetworkFailure {
    pub code: FailureCode,
    /// For `native_keys_pending` `empty` or `self_missing`; for
    /// `peer_not_native` the refused member's node ID; for the start
    /// failures the reason. Never carries the network secret.
    pub detail: String,
}

/// The `network.failure.code` values the management API gives.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum FailureCode {
    /// A managed network whose native key list is absent, empty or lacks
    /// this node (spec §8.3.1 rule 1): it waits, not running.
    NativeKeysPending,
    /// The last member refused for a key off the native key list.
    PeerNotNative,
    PortInUse,
    TunInUse,
    /// The virtual subnet overlaps one another network of this node runs
    /// on; `detail` is the subnet.
    RouteOverlap,
    /// The virtual address is one another network of this node uses.
    AddressInUse,
    /// None of the configured peers has been reached since the network
    /// started.
    UnreachablePeers,
    PermissionDenied,
    /// Any other reason the network could not start.
    StartRefused,
}

/// One managed network.
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct ManagedNetworkStatus {
    pub tag: String,
    pub running: bool,
    /// Why the network does not run; empty while it runs.
    pub error: String,
    /// This node's virtual address with the network's prefix length, for
    /// example `10.150.0.5/16`; empty when none is set.
    #[serde(serialize_with = "interface_address")]
    pub address: Option<IpNet>,
    /// Whether the network runs in the secure mode.
    pub forward_secrecy: bool,
    /// `null`, or why the network waits or what it last refused.
    pub failure: Option<NetworkFailure>,
    /// Reachable members (requirement R16).
    pub peers: Vec<ManagedPeer>,
    /// Subnet advertisements refused because they lie outside the intranet
    /// range or collide with a local network (R16, R17).
    pub rejected_advertisements: u64,
    /// Advertised subnets that overlap another advertisement or a local
    /// network (R17).
    #[serde(serialize_with = "display_all")]
    pub overlaps: Vec<IpNet>,
    pub alerts: Vec<Alert>,
    /// The custom paths and their states, in configuration order (spec
    /// §17.2.7). Members are named by their virtual address, as in `peers`.
    pub paths: Vec<ManagedPath>,
    /// `externalBridge` (spec §15.12 item 8, three states): absent while
    /// unknown, `null` when the network surely has no bridge, otherwise
    /// the bridge in force.
    #[serde(rename = "externalBridge", skip_serializing_if = "Option::is_none")]
    pub external_bridge: Option<Option<ExternalBridgeStatus>>,
}

/// The bridge in force in one network: digests of the lists whose rules
/// are all loaded (`docs/architecture/mesh-status.md`, `externalBridge`).
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ExternalBridgeStatus {
    pub allow_digest: String,
    pub allow_count: usize,
    pub routes_digest: String,
    /// RFC 3339, UTC.
    pub applied_at: String,
}

impl ManagedNetworkStatus {
    /// A network that is not running, with the reason.
    pub fn stopped(tag: impl Into<String>, error: impl Into<String>) -> Self {
        Self {
            tag: tag.into(),
            running: false,
            error: error.into(),
            address: None,
            forward_secrecy: false,
            failure: None,
            peers: Vec::new(),
            rejected_advertisements: 0,
            overlaps: Vec::new(),
            alerts: Vec::new(),
            paths: Vec::new(),
            external_bridge: None,
        }
    }
}

/// One reachable member of a managed network.
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct ManagedPeer {
    /// The member's virtual address.
    pub address: IpAddr,
    /// Subnets the member advertises and this node accepted.
    #[serde(serialize_with = "display_all")]
    pub subnets: Vec<IpNet>,
    /// Virtual addresses of the relays on the path, first hop first; empty
    /// for a direct connection.
    pub via: Vec<IpAddr>,
    /// Hops to the member; 1 for a direct connection.
    pub hops: u32,
    /// Round-trip time in milliseconds; `null` before the first measurement.
    pub latency_ms: Option<u32>,
    /// Whether the session with this member has forward secrecy.
    pub forward_secrecy: bool,
    /// `auto`, `custom`, `first_hop_only` or `fallback`: the state of the
    /// custom path to this member (`mesh-status.md`, `members[].pathState`).
    pub path_state: &'static str,
    /// The node that path names as unreachable; `null` when none.
    pub unreachable: Option<IpAddr>,
}

/// One custom path of a managed network (`mesh-status.md`, `paths[]`).
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct ManagedPath {
    /// `peer:<address>` or `subnet:<network>`; stays when the list changes.
    pub id: String,
    pub target: ManagedPathTarget,
    /// The waypoints' virtual addresses, in configuration order.
    pub via: Vec<IpAddr>,
    /// `pending`, `active`, `first_hop_only` or `fallback`.
    pub state: &'static str,
    /// The node `reason` is about; `null` when none.
    pub unreachable: Option<IpAddr>,
    /// Why the path fell back or is only partly kept; `null` otherwise.
    pub reason: Option<&'static str>,
}

/// The target of a [`ManagedPath`]: `{"peer": address}` or
/// `{"subnet": network}`.
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum ManagedPathTarget {
    Peer(IpAddr),
    Subnet(String),
}

/// Something the network's operator should act on.
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct Alert {
    pub code: AlertCode,
    /// The address concerned; empty when the alert is not about one.
    #[serde(serialize_with = "optional_address")]
    pub address: Option<IpAddr>,
    /// The member concerned (its instance ID); empty when none.
    pub peer: String,
    /// For people only; for [`AlertCode::StartRefused`] the reason, for
    /// example the port in use. Never carries the network secret.
    pub detail: String,
}

/// Alert codes the kernel raises. The agent adds codes of its own
/// (`unsupported`, `takeover_pending`); readers show unknown codes as they
/// are.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum AlertCode {
    /// Another member uses this node's virtual address (R29).
    AddressConflict,
    /// A member uses an address the panel did not assign (R29).
    AddressUnmanaged,
    /// The kernel refused to start the network (R12): a port in use, a
    /// virtual interface or route conflict, or the same node identity
    /// already online; `detail` says which.
    StartRefused,
    /// More subnets are routable than the system routes take; `detail` is
    /// how many were left out.
    SystemRoutesTruncated,
    /// A member announces another static key than the one bound to its
    /// node ID; the announcement is not used. `detail` is its node ID.
    PeerKeyChanged,
    /// RPC bodies over 4 MiB were not sent; `detail` is how many.
    RpcOversize,
    /// The network is larger than route synchronisation carries: a call
    /// over 8 MiB was dropped (spec §11.2), or a neighbour did not take the
    /// connection graph in time and the session was closed (§12.2). `peer`
    /// is empty; `detail` says which, with the node ID.
    SyncOversize,
    /// An advertised subnet overlaps a route another mesh program carries
    /// on this machine, so it is kept local (spec §15.4); `detail` is the
    /// subnet.
    ForeignRouteOverlap,
    /// The bridge's new rules or the deletion of tracked connections
    /// failed; the old rules and `externalBridge` stay (spec §15.12).
    ExternalBridgeApplyFailed,
    /// The bridge has IPv6 routes but the host does not forward IPv6.
    ExternalBridgeIpv6ForwardingOff,
    /// Another process holds the host's bridge lock: this one does not
    /// bridge, declare the capability or clean up (spec §15.12 item 9).
    ExternalBridgeLockHeld,
}

/// Why a `PUT /v1/mesh` was not applied.
#[derive(Debug, PartialEq, Eq)]
pub enum ApplyError {
    /// The request is invalid as a whole and nothing changed (answers 400).
    /// The message must not carry the secret.
    Invalid(String),
    /// The kernel failed to apply it (answers 500).
    Failed(String),
}

impl fmt::Display for ApplyError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Invalid(message) | Self::Failed(message) => f.write_str(message),
        }
    }
}

impl std::error::Error for ApplyError {}

/// How this node routes an accepted subnet that overlaps one of its own
/// networks (`mesh_set_subnet_route`, spec §15.4): `local` (the default)
/// keeps it out of the mesh, `mesh` routes and installs it all the same.
#[derive(Clone, Copy, Debug, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum SubnetRoute {
    Local,
    Mesh,
}

/// Why a subnet route override was not taken.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum OverrideError {
    /// No network has the tag (answers 404).
    UnknownNetwork,
    /// The override is refused, for example past [`MAX_ROUTE_OVERRIDES`]
    /// (answers 400).
    Invalid(String),
    /// It could not be saved (answers 500); nothing changed.
    Failed(String),
}

/// Subnets one network may route through the mesh against the overlap
/// rule.
pub const MAX_ROUTE_OVERRIDES: usize = 256;

/// A boxed future, so [`MeshControl`] stays object safe.
pub type BoxFuture<'a, T> = Pin<Box<dyn Future<Output = T> + Send + 'a>>;

/// The mesh as the management API drives it. The node program installs one
/// implementation; without it the kernel does not list `mesh` in its
/// features and `/v1/mesh` answers 404.
pub trait MeshControl: Send + Sync {
    /// Feature names this implementation adds to `GET /v1/status`:
    /// at least `mesh`; `mesh_dns` once the network config takes `dns`.
    fn features(&self) -> &'static [&'static str];

    /// The current status.
    fn status(&self) -> ManagedStatus;

    /// Replaces the running networks with `networks` (empty stops them
    /// all) and the backbone with `backbone` (`None` stops it). Networks
    /// whose settings did not change keep running without interruption.
    /// A network that cannot start is not an error: it is reported with
    /// `running: false` and a [`AlertCode::StartRefused`] alert; a backbone
    /// that cannot start is reported with its `failure`. Calls are not
    /// concurrent: the management API serializes them.
    fn apply(
        &self,
        networks: Vec<ManagedNetwork>,
        backbone: Option<ManagedBackbone>,
    ) -> BoxFuture<'_, Result<ManagedStatus, ApplyError>>;

    /// Hands over the top-level `region` object of the last `PUT`
    /// (appendix D.9.1; `None` when it had none or `null`), after
    /// [`MeshControl::apply`] of the same request. Only called when
    /// [`MeshControl::features`] lists `mesh_region_probe`; the management
    /// API refuses the object otherwise.
    fn set_region(
        &self,
        region: Option<crate::region::directory::RegionSection>,
    ) -> BoxFuture<'_, ()> {
        let _ = region;
        Box::pin(async {})
    }

    /// Saves a local override for the network `tag` (spec §15.4): with
    /// [`SubnetRoute::Mesh`] the accepted subnet equal to `subnet` is routed
    /// and installed although it overlaps a network of this machine;
    /// [`SubnetRoute::Local`] withdraws that. It outlives restarts and the
    /// network's configuration, which it does not change.
    fn set_subnet_route(
        &self,
        tag: String,
        subnet: IpNet,
        route: SubnetRoute,
    ) -> BoxFuture<'_, Result<(), OverrideError>> {
        let _ = (tag, subnet, route);
        Box::pin(async {
            Err(OverrideError::Invalid(
                "subnet route overrides are not supported".to_owned(),
            ))
        })
    }
}

fn interface_address<S: Serializer>(address: &Option<IpNet>, s: S) -> Result<S::Ok, S::Error> {
    match address {
        Some(net) => s.collect_str(&format_args!("{}/{}", net.address(), net.prefix())),
        None => s.serialize_str(""),
    }
}

fn optional_address<S: Serializer>(address: &Option<IpAddr>, s: S) -> Result<S::Ok, S::Error> {
    match address {
        Some(address) => s.collect_str(address),
        None => s.serialize_str(""),
    }
}

fn display_all<S: Serializer, T: fmt::Display>(items: &[T], s: S) -> Result<S::Ok, S::Error> {
    s.collect_seq(items.iter().map(ToString::to_string))
}

